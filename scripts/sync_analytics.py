# -- reading redis ------------------------------------------------------------


class Unreachable(Exception):
    """The store could not be read. Distinct from the store being empty.

    Both used to return {}, so a day that could not be fetched was archived as a
    day on which nothing happened, and the sync said so and exited zero. The
    whole point of this script is that it runs before Redis prunes; a silent
    failure to reach it is the one outcome that must be loud.
    """


def fetch_day(url: str, token: str, day: str) -> dict[str, int]:
    """One day's counters, or {} when the key has expired or never existed."""
    key = urllib.parse.quote(f"a:d:{day}", safe="")
    request = urllib.request.Request(
        f"{url}/hgetall/{key}", headers={"Authorization": f"Bearer {token}"}
    )
    try:
        with urllib.request.urlopen(request, timeout=20) as response:
            body = json.loads(response.read())
    except (urllib.error.URLError, TimeoutError, ValueError) as exc:
        raise Unreachable(f"{day}: {exc}") from exc
    # Upstash answers HTTP 200 with {"error": ...} for a rejected command. Read as
    # "no result" that was archived as a day nothing happened: the silent loss
    # Unreachable exists to prevent.
    if not isinstance(body, dict) or "error" in body:
        raise Unreachable(f"{day}: Redis returned an error: {str(body.get('error') if isinstance(body, dict) else body)[:200]}")
    flat = body.get("result")
    if flat is None:
        return {}  # expired, or never written
    if not isinstance(flat, list) or len(flat) % 2:
        raise Unreachable(f"{day}: unexpected reply shape from Redis")
    counters = {}
    for field, value in zip(flat[::2], flat[1::2]):
        try:
            counters[str(field)] = int(value)
        except (TypeError, ValueError):
            raise Unreachable(f"{day}: non-numeric counter {str(field)[:60]!r}") from None
        if counters[str(field)] < 0:
            raise Unreachable(f"{day}: negative counter {str(field)[:60]!r}")
    return counters


def namespace() -> str:
    """The key prefix the site writes under, derived exactly as lib/analytics.ts does."""
    ns = os.environ.get("ANALYTICS_NAMESPACE") or "a"
    if ns != "a" and not re.fullmatch(r"test-[a-z0-9-]{8,64}", ns):
        raise Unreachable(f"invalid ANALYTICS_NAMESPACE {ns[:80]!r}")
    return ns


def command(url: str, token: str, *args: object) -> object:
    """One Redis command over the REST API, as strict as fetch_day."""
    request = urllib.request.Request(
        url, data=json.dumps([str(a) for a in args]).encode(),
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=20) as response:
            body = json.loads(response.read())
    except (urllib.error.URLError, TimeoutError, ValueError) as exc:
        raise Unreachable(f"{args[0]}: {exc}") from exc
    if not isinstance(body, dict) or "error" in body or "result" not in body:
        raise Unreachable(f"{args[0]}: Redis returned an error: {str(body.get('error') if isinstance(body, dict) else body)[:200]}")
    return body["result"]


# -- the event journal --------------------------------------------------------

PAGE = 500  # entries per XRANGE; fixed so a rerun re-reads the same ranges
ZERO = (0, 0)


def sid(text: object) -> tuple[int, int]:
    """A stream id as an exact (ms, seq) pair: never a float, never a string compare."""
    m = re.fullmatch(r"(\d+)-(\d+)", str(text))
    if not m:
        raise Unreachable(f"malformed stream id {str(text)[:60]!r}")
    return int(m[1]), int(m[2])


def fmt(pair: tuple[int, int]) -> str:
    return f"{pair[0]}-{pair[1]}"


def entries(reply: object) -> list[tuple[tuple[int, int], dict[str, str]]]:
    """An XRANGE/XREVRANGE reply, validated: [[id, [field, value, ...]], ...]."""
    if not isinstance(reply, list):
        raise Unreachable("unexpected stream reply shape from Redis")
    out = []
    for item in reply:
        if not (isinstance(item, list) and len(item) == 2 and isinstance(item[1], list) and len(item[1]) % 2 == 0):
            raise Unreachable("unexpected stream entry shape from Redis")
        flat = item[1]
        out.append((sid(item[0]), {str(k): str(v) for k, v in zip(flat[::2], flat[1::2])}))
    return out


def event(stream_id: tuple[int, int], fields: dict[str, str]) -> dict:
    """One journal entry back in the feed's shape (lib/analytics.ts writes absent = null)."""
    out: dict = {"stream_id": fmt(stream_id), "id": fields.get("id")}
    for name in ("path", "agent", "vendor", "purpose", "event", "referrer"):
        out[name] = fields.get(name)
    try:
        out["at"] = int(fields["at"])
    except (KeyError, ValueError):
        out["at"] = None
    out["missing"] = fields.get("missing") == "true"
    for name, value in fields.items():  # anything newer than this exporter, kept raw
        out.setdefault(name, value)
    return out


def _install(path: Path, text: str) -> None:
    """Flush and atomically move into place; a crash leaves the old file or none."""
    tmp = path.with_name(path.name + ".tmp")
    with open(tmp, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(tmp, path)


def archived_ids(events_dir: Path) -> set[str]:
    """Every logical event id already in a segment. A damaged segment is reported, not skipped."""
    # ponytail: reads every segment each run; an index file if this ever gets slow (millions of events).
    seen: set[str] = set()
    for path in sorted(events_dir.glob("*/*.jsonl")):
        for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            try:
                row = json.loads(line)
                seen.add(row["id"] or row["stream_id"])
            except (ValueError, KeyError, TypeError):
                raise Unreachable(f"corrupt segment {path.parent.name}/{path.name} line {n}") from None
    return seen


def export_events(url: str, token: str, out_dir: Path, ns: str) -> tuple[int, str]:
    """Copy `${ns}:events` into immutable vault segments; return (exported, last stream id).

    Segment first, cursor second: a crash between them re-reads the same range on
    the next run, and every event in it is skipped by its logical id. Nothing is
    ever deleted from the stream here.
    """
    key = f"{ns}:events"
    events_dir = out_dir / "events"
    events_dir.mkdir(parents=True, exist_ok=True)
    cursor_path = events_dir / "cursor.json"
    cursor, exported = ZERO, 0
    if cursor_path.exists():
        try:
            saved = json.loads(cursor_path.read_text(encoding="utf-8"))
            if saved["namespace"] != ns:
                raise Unreachable(f"cursor belongs to namespace {saved['namespace']!r}, not {ns!r}")
            cursor, exported = sid(saved["last_id"]), int(saved.get("exported", 0))
        except (ValueError, KeyError, TypeError) as exc:
            raise Unreachable(f"damaged cursor {cursor_path}: {exc}") from None

    latest = entries(command(url, token, "XREVRANGE", key, "+", "-", "COUNT", 1))
    high = latest[0][0] if latest else ZERO  # finite high-water mark for this run
    if cursor > high:
        raise Unreachable(f"stream reset: cursor {fmt(cursor)} is past the stream's last id {fmt(high)}; "
                          f"not moving the cursor -- investigate before exporting")

    seen = archived_ids(events_dir)
    fresh = 0
    while cursor < high:
        page = entries(command(url, token, "XRANGE", key, f"({fmt(cursor)}", fmt(high), "COUNT", PAGE))
        if not page:
            break
        ids = [i for i, _ in page]
        if ids[0] <= cursor or ids != sorted(set(ids)) or ids[-1] > high:
            raise Unreachable(f"stream returned out-of-range ids after {fmt(cursor)}")
        rows = []
        for stream_id, fields in page:
            row = event(stream_id, fields)
            logical = row["id"] or row["stream_id"]
            if logical in seen:
                continue  # a retried XADD, or a range already archived before a crash
            seen.add(logical)
            rows.append(row)
        if rows:
            first, last = ids[0], ids[-1]
            day = datetime.fromtimestamp(first[0] / 1000, timezone.utc).date().isoformat()
            path = events_dir / day / f"{fmt(first)}-{fmt(last)}.jsonl"
            path.parent.mkdir(exist_ok=True)
            text = "".join(json.dumps(r, sort_keys=True) + "\n" for r in rows)
            if path.exists() and path.read_text(encoding="utf-8") != text:
                raise Unreachable(f"segment {day}/{path.name} exists with different contents; not overwriting")
            if not path.exists():
                _install(path, text)
            fresh += len(rows)
        cursor = ids[-1]
        exported += len(rows)
        _install(cursor_path, json.dumps({"namespace": ns, "last_id": fmt(cursor), "exported": exported}) + "\n")
    return fresh, fmt(cursor)


def split(counters: dict[str, int], kind: str) -> dict[str, int]:
    prefix = f"{kind}:"
    return {
        k[len(prefix):]: v
        for k, v in counters.items()
        if k.startswith(prefix) and isinstance(v, int)
    }


# -- writing the vault --------------------------------------------------------


def snapshot(counters: dict[str, int], meta: dict[str, dict[str, str]]) -> dict:
    """The vendor and purpose of every agent seen that day, frozen.

    Without this, a note is relabelled from whatever `agents.json` says at the
    moment it is rendered. Correcting a vendor, or moving an agent from training
    to search, silently rewrote history that the raw counters cannot support --
    and left the per-agent labels disagreeing with the aggregate purpose totals
    stored beside them, which were never rewritten.

    Written once, when the day is first archived. Days captured before this
    existed have no snapshot and fall back to the live registry, which is the
    old behaviour and the best that can be done for them.
    """
    seen = {k[2:] for k in counters if k.startswith("g:")}
    # Only what a note renders. The registry entry also carries the match
    # pattern, which is how the agent was identified rather than anything about
    # it, and has no business in a record of what happened.
    return {
        name: {"vendor": meta[name]["vendor"], "purpose": meta[name]["purpose"]}
        for name in sorted(seen)
        if name in meta
    }


def well_formed(record) -> bool:
    """An archived day: whole, non-negative counters, plus an optional `_agents`
    mapping of name -> {vendor, purpose} strings. Anything else (NaN, Infinity,
    booleans, nested junk) is damage the readers would trip over."""
    if not isinstance(record, dict):
        return False
    counters_ok = all(type(v) is int and v >= 0 for k, v in record.items() if not k.startswith("_"))
    agents = record.get("_agents", {})
    agents_ok = isinstance(agents, dict) and all(
        isinstance(info, dict) and all(isinstance(info.get(f, ""), str) for f in ("vendor", "purpose"))
        for info in agents.values())
    return counters_ok and agents_ok


def write_raw(
    out_dir: Path, day: str, counters: dict[str, int], meta: dict[str, dict[str, str]]
) -> bool:
    """Store the day, unless what we have is smaller than what is already there.

    A day drops out of Redis after ninety days and comes back as {}. Writing
    that over a good archive would quietly delete the history this script exists
    to keep, so the archive only ever grows.

    Written to a temporary file and moved into place, because this is the record
    and a half-written one is worse than yesterday's: an interrupted run used to
    be able to leave a truncated JSON that every later run then read as a
    smaller day and refused to replace.
    """
    path = out_dir / "data" / f"{day}.json"
    path.parent.mkdir(parents=True, exist_ok=True)

    counted = {k: v for k, v in counters.items() if not k.startswith("_")}
    existing = {}
    if path.exists():
        try:
            existing = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            existing = {}
        damaged = not well_formed(existing)
        if not isinstance(existing, dict):
            existing = {}  # a damaged file is replaced, not allowed to stop every later sync
        previous = {k: v for k, v in existing.items() if not k.startswith("_") and type(v) is int and v >= 0}
        # The archive only grows: a smaller day never replaces a larger one, and
        # an identical one is skipped unless the file needs repairing.
        if any(counted.get(k, 0) < v for k, v in previous.items()) or (previous == counted and not damaged):
            return False

    payload = dict(counted)
    # Earlier snapshots win (a later agents.json edit must not relabel a day),
    # but only well-formed ones: a damaged entry is replaced by today's.
    kept = existing.get("_agents") if isinstance(existing.get("_agents"), dict) else {}
    kept = {name: info for name, info in kept.items() if well_formed({"_agents": {name: info}})}
    payload["_agents"] = {**snapshot(counted, meta), **kept}

    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    tmp.replace(path)
    return True


def cell(text: str) -> str:
    """One table cell, safe to put between pipes.

    Every label here arrives from the public internet: a path, a referrer, a
    comparison, a click. The site escapes them when it renders, but a Markdown
    table is a second boundary and this file is the only thing standing at it.
    A pipe splits the row, a newline ends it, and backticks or brackets render
    as something other than the text that was counted.

    Escaped rather than stripped, so what is shown is still what was recorded.
    """
    out = str(text).replace("\\", "\\\\").replace("|", "\\|")
    out = out.replace("\r", " ").replace("\n", " ")
    out = out.replace("`", "\\`").replace("[", "\\[").replace("]", "\\]")
    out = out.replace("<", "&lt;").replace(">", "&gt;")
    return out[:200] if len(out) > 200 else out


def table(rows: dict[str, int], head: tuple[str, str], limit: int = 25) -> list[str]:
    if not rows:
        return ["_Nothing._", ""]
    out = [f"| {head[0]} | {head[1]} |", "|---|---:|"]
    for name, count in sorted(rows.items(), key=lambda kv: -kv[1])[:limit]:
        out.append(f"| {cell(name)} | {int(count)} |")
    out.append("")
    return out


def _sentence(purposes: dict[str, int]) -> str:
    """The split, in prose that agrees with itself at one as well as at ten."""
    live, training, search = (purposes.get(k, 0) for k in ("live", "training", "search"))

    def crawls(n: int, kind: str) -> str:
        return f"{n} was a {kind} crawl" if n == 1 else f"{n} were {kind} crawls"

    lead = (
        f"{live} of the agent hits was an assistant"
        if live == 1
        else f"{live} of the agent hits were assistants"
    )
    return (
        f"{lead} reading this page to answer a person. "
        f"{crawls(training, 'training or indexing')}, "
        f"{crawls(search, 'search')}."
    )


def day_note(day: str, counters: dict[str, int], meta: dict[str, dict[str, str]]) -> str:
    agents = split(counters, "g")
    purposes = split(counters, "p")
    totals = split(counters, "t")

    lines = [
        "---",
        STAMP,
        f"date: {day}",
        f"agents: {totals.get('agent', 0)}",
        f"humans: {totals.get('human', 0)}",
        f"answering: {purposes.get('live', 0)}",
        "---",
        "",
        f"# Audience — {day}",
        "",
        f"**{totals.get('agent', 0)} agent hits · {totals.get('human', 0)} human views**",
        "",
        _sentence(purposes),
        "",
        "## Which assistants",
        "",
    ]

    if agents:
        lines += ["| Agent | Vendor | Why | Hits |", "|---|---|---|---:|"]
        for name, count in sorted(agents.items(), key=lambda kv: -kv[1]):
            info = meta.get(name, {})
            why = PURPOSE_WORD.get(info.get("purpose", ""), "—")
            lines.append(
                f"| {cell(name)} | {cell(info.get('vendor', '—'))} | {why} | {int(count)} |"
            )
        lines.append("")
    else:
        lines += ["_No agent identified itself._", ""]

    pairs = {k.replace(PAIR_SEP, " → "): v for k, v in split(counters, "gp").items()}
    lines += ["## What the agents read", ""] + table(pairs, ("Agent → page", "Hits"))
    lines += ["## Brands looked up", ""] + table(split(counters, "b"), ("Brand", "Views"))
    by_agents = split(counters, "ba")
    if by_agents:
        lines += ["## Brands looked up by an assistant", ""] + table(
            by_agents, ("Brand", "Reads")
        )
    lines += ["## Compared against each other", ""] + table(
        split(counters, "m"), ("Pair", "Times")
    )
    lines += ["## Pages people read", ""] + table(split(counters, "v"), ("Page", "Views"))
    lines += ["## Clicks", ""] + table(split(counters, "c"), ("Element", "Clicks"))

    referrers = split(counters, "r")
    assistants = {k: v for k, v in referrers.items() if is_assistant(k)}
    if assistants:
        lines += ["## Arrived from an assistant", ""] + table(
            assistants, ("Assistant", "Visits")
        )
    lines += ["## Came from", ""] + table(referrers, ("Referrer", "Visits"))

    missing = split(counters, "x")
    if missing:
        lines += ["## Asked for, and not here", ""] + table(missing, ("Path", "Times"))

    lines += [
        "---",
        "",
        "Counted by the site itself; agents from the request, people from a beacon.",
        "No cookie, no identifier and no address is stored. A user agent is",
        "self-declared and can be forged, so read these as what the client said it",
        "was rather than as proof.",
        "",
        "Part of [[Projects/Unprompted/MOC|Unprompted]].",
        "",
    ]
    return "\n".join(lines)


def write_index(out_dir: Path, meta: dict[str, dict[str, str]]) -> None:
    """Every archived day, plus all-time totals derived from the raw files."""
    files = sorted((out_dir / "data").glob("*.json"))
    life: Counter[str] = Counter()
    damaged = 0
    for path in files:
        try:
            record = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            record = None
        if not well_formed(record):
            damaged += 1
            continue
        for field, count in record.items():
            if not field.startswith("_"):
                life[field] += int(count)
    if damaged:
        print(f"  all-time totals exclude {damaged} damaged archive file(s)", file=sys.stderr)

    def of(kind: str) -> dict[str, int]:
        return {k[len(kind) + 1:]: v for k, v in life.items() if k.startswith(f"{kind}:")}

    totals, purposes = of("t"), of("p")
    lines = [
        "---",
        "type: index",
        "---",
        "",
        "# Unprompted, audience",
        "",
        f"All time, across {len(files)} archived day(s).",
        "",
        *([f"_Every total on this page excludes {damaged} damaged archive file(s) in `data/`, so all of them are incomplete._", ""]
          if damaged else []),
        # One line, deliberately. The ownership check below is a substring test,
        # and wrapping this sentence across two lines meant the stamp never
        # appeared contiguously: the script refused to update its own index.
        f"{INDEX_STAMP} in the Unprompted repository. Edits here are overwritten;",
        "the day notes and `data/` beside them are the record.",
        "",
        f"**{totals.get('agent', 0)} agent hits · {totals.get('human', 0)} human views**",
        "",
        # Same sentence builder as a day note, so the counts agree with their
        # verbs in both places rather than only in one.
        _sentence(purposes).replace("the agent hits", "all agent hits").replace(
            "this page", "a page here"
        ),
        "",
        "## Which assistants, all time",
        "",
    ]

    agents = of("g")
    if agents:
        lines += ["| Agent | Vendor | Why | Hits |", "|---|---|---|---:|"]
        for name, count in sorted(agents.items(), key=lambda kv: -kv[1]):
            info = meta.get(name, {})
            lines.append(
                f"| {cell(name)} | {cell(info.get('vendor', '—'))} | "
                f"{PURPOSE_WORD.get(info.get('purpose', ''), '—')} | {int(count)} |"
            )
        lines.append("")
    else:
        lines += ["_Nothing archived yet._", ""]

    lines += ["## Brands looked up, all time", ""] + table(of("b"), ("Brand", "Views"))
    by_agents = of("ba")
    if by_agents:
        lines += ["## Brands looked up by an assistant, all time", ""] + table(
            by_agents, ("Brand", "Reads")
        )
    lines += ["## Compared against each other, all time", ""] + table(
        of("m"), ("Pair", "Times")
    )
    lines += ["## Pages, all time", ""] + table(of("v"), ("Page", "Views"))
    lines += ["## Days", ""]
    for path in reversed(files):
        lines.append(f"- [[Audience {path.stem}]]")
    lines += [
        "",
        "---",
        "",
        "Live dashboard at https://unprompted.report/admin",
        "",
        "Part of [[Projects/Unprompted/MOC|Unprompted]].",
        "",
    ]

    index = out_dir / "Audience Index.md"
    if index.exists() and INDEX_STAMP not in index.read_text(encoding="utf-8"):
        print(f"skip (not ours): {index.name}", file=sys.stderr)
        return
    index.write_text("\n".join(lines), encoding="utf-8")


def _main(detail: dict) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vault", type=Path, default=DEFAULT_VAULT)
    parser.add_argument(
        "--days",
        type=int,
        default=90,
        help="how far back to pull from Redis (it keeps 90)",
    )
    args = parser.parse_args()

    if not args.vault.is_dir():
        print(f"no vault at {args.vault}", file=sys.stderr)
        return 1

    load_local_env()

    url = (os.environ.get("KV_REST_API_URL") or "").rstrip("/")
    token = os.environ.get("KV_REST_API_TOKEN") or ""
    if not url or not token:
        print(
            "KV_REST_API_URL and KV_REST_API_TOKEN are not set, so there is "
            "nothing to archive. Run `vercel env pull`.",
            file=sys.stderr,
        )
        return 1

    out_dir = args.vault / FOLDER
    out_dir.mkdir(parents=True, exist_ok=True)
    meta = registry()

    today = datetime.now(timezone.utc).date()  # the site counts days in UTC
    fresh = 0
    unreachable = 0
    for offset in range(args.days):
        day = (today - timedelta(days=offset)).isoformat()
        try:
            counters = fetch_day(url, token, day)
        except Unreachable as exc:
            unreachable += 1
            print(f"  could not read {exc}", file=sys.stderr)
            continue
        if not counters:
            continue
        if write_raw(out_dir, day, counters, meta):
            fresh += 1

    # Notes are rebuilt from the archive rather than from Redis, so a day that
    # has aged out of the cache still renders from what was captured.
    written = 0
    for path in sorted((out_dir / "data").glob("*.json")):
        day = path.stem
        try:
            counters = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            counters = None
        if not well_formed(counters):
            # Kept as evidence (it may hold a day Redis no longer has), not rendered.
            print(f"  skip damaged archive file: {path.name}", file=sys.stderr)
            continue
        dest = out_dir / f"Audience {day}.md"
        # The day's own snapshot, so a later edit to agents.json cannot relabel
        # it. Days archived before snapshots existed fall back to the registry.
        frozen = counters.get("_agents") or {}
        body = day_note(day, counters, {**meta, **frozen} if frozen else meta)
        if dest.exists():
            existing = dest.read_text(encoding="utf-8")
            if STAMP not in existing:
                print(f"skip (not ours): {dest.name}", file=sys.stderr)
                continue
            if existing == body:
                continue
        dest.write_text(body, encoding="utf-8")
        written += 1

    write_index(out_dir, meta)
    print(f"{fresh} day(s) archived, {written} note(s) written to {out_dir}")

    # The journal: every accepted event, not just the counters and the last 200.
    stream_failed = False
    try:
        count, last = export_events(url, token, out_dir, namespace())
        detail.update(events_exported=count, stream_last_id=last)
        print(f"{count} event(s) exported, stream through {last}")
    except Unreachable as exc:
        stream_failed = True
        print(f"FAILED: event journal export: {exc}", file=sys.stderr)

    if stream_failed and not unreachable:
        return 1
    if unreachable:
        print(
            f"FAILED: {unreachable} day(s) could not be read from Redis. Nothing "
            f"was lost yet -- Redis keeps ninety days -- but this must succeed "
            f"before then or that history is gone.",
            file=sys.stderr,
        )
        return 1
    return 0


def main() -> int:
    """_main, with its outcome recorded for readiness and the mid-week check."""
    from unprompted.storage import record_status
    status_dir = Path(__file__).resolve().parents[1] / ".unprompted" / "status"
    detail: dict = {}
    try:
        code = _main(detail)
    except Exception as exc:
        record_status(status_dir, "sync_analytics", False, f"{type(exc).__name__}: {exc}", **detail)
        raise
    record_status(status_dir, "sync_analytics", code == 0, "" if code == 0 else f"exit {code}", **detail,
                  # UTC, the day boundary the site counts by (lib/analytics.ts).
                  covered_through=datetime.now(timezone.utc).date().isoformat() if code == 0 else None)
    return code


if __name__ == "__main__":
    raise SystemExit(main())
