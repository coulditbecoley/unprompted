"""Archive the audience counters into the Obsidian vault.

Redis holds ninety days and then prunes itself, which is right for a cache and
wrong for a record. This copies each day out before it expires, so the history
outlives both the cache and the repository — the same reason the weekly notes
are mirrored by `sync_vault.py`.

Three things are written, and the order matters:

    Analytics/data/<date>.json   the raw counters, exactly as stored. The
                                 source of truth. Never regenerated from the
                                 notes, only from Redis.
    Analytics/<date>.md          that day, readable, for the graph and search.
    Analytics/Audience Index.md  every day plus all-time totals, derived from
                                 every JSON file present.

Separately, the event journal (`<namespace>:events`, a Redis stream the site
never trims) is copied out page by page:

    Analytics/events/<date>/<first-id>-<last-id>.jsonl   immutable segments,
                                 one event per line, deduplicated by event id.
    Analytics/events/cursor.json the last stream id exported. Advanced only
                                 after its segment is installed.

Derived files are rebuilt from the JSON on every run, so a change to how a note
reads is one run away from applying to the whole history. The JSON is only ever
written for a day that is still in Redis, and never overwritten with less than
it already has: a day that has aged out of the cache keeps whatever was captured
while it was there.

Idempotent, and safe to run any number of times.

    python scripts/sync_analytics.py [--vault PATH] [--days 90]
"""

